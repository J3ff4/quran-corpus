// Generates src/mushaf/fontManifest.generated.ts. Metro resolves `require` at
// build time from a string literal, so 604 literals is the only way to reach
// 604 assets -- a template string silently resolves to nothing.
//
// The manifest is committed; the fonts it points at are NOT (see .gitignore).
// A build without them fails loudly at bundle time, which is the intent.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const lines = [];
for (let page = 1; page <= 604; page++) {
  const p = String(page).padStart(3, '0');
  lines.push(`  ${page}: require('../../assets/fonts/mushaf/p${p}.ttf'),`);
}

const contents = `// AUTO-GENERATED by scripts/generate-mushaf-font-manifest.mjs — do not edit by hand.
// Run \`pnpm generate:mushaf-manifest\` to regenerate.
//
// The .ttf files are gitignored and produced by \`uv run scraper mushaf-fonts\`.
export const MUSHAF_FONT_ASSETS: Record<number, number> = {
${lines.join('\n')}
};
`;

writeFileSync(join(here, '..', 'src', 'mushaf', 'fontManifest.generated.ts'), contents, 'utf-8');
process.stdout.write('Generated src/mushaf/fontManifest.generated.ts (604 entries)\n');
